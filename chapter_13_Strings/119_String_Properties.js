let str = "Hello World";
console.log(str.length); // length property gives the number of characters in the string

//Access by index
console.log(str[0]); // H
console.log(str[6]); // W
console.log(str[11]); // undefined (out of bounds)  
console.log(str[-1]); // undefined (negative index does not work in JavaScript)

console.log(str.charAt(0)); // H
console.log(str.charCodeAt(0)); // 72 (ASCII code for 'H')



