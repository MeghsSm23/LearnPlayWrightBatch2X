//post-increment operator (a++)
//The post-increment operator (a++) is used to increment the value of a variable by 1, but it returns the original value before the increment. This means that when you use a++ in an expression, it will first return the current value of a and then increment it by 1.

let a_post = 10;
let b_post = a_post++;
console.log(a_post);
console.log(b_post);

