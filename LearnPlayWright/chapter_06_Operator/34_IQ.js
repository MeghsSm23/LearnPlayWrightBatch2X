//Compound assignment operator
// Compound assignment operators combine an arithmetic operation with assignment. 
// They provide a shorthand way to update the value of a variable based on its current value. 
// Here are some examples:

let x = 10;
x += 10;
console.log(x) // 20


x -= 3;
console.log(x) // 17

x /= 4;
console.log(x) // 4.25

x *= 4;
console.log(x) // 17

x %= 2;
console.log(x) // 1

