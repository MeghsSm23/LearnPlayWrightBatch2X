//modulus operator
// The modulus operator (%) returns the remainder of a division operation. 
// It is used to find out how many times one number can be divided by another and what is left over. 
// Here are some examples:

let result = 13 % 7;
console.log(result); // Output: 6

console.log(101 % 2); // Output: 1  
console.log(100 % 2); // Output: 1

console.log(37 % 2); // Output: 3


